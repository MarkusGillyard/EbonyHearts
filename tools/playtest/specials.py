#!/usr/bin/env python3
"""Every special of a fighter, entered through real keys in Training.

    specials.py script <fighter>            prints an xdrive script (player 1, left keyboard set)
    specials.py check <fighter> <trace>     reports which specials started, from the game's trace

Each special starts from a training reset (F4) with player 1 on the left, facing right; command
grabs walk in first, air specials jump first.
"""
import json
import os
import sys

ROOT = os.path.join(os.path.dirname(__file__), "..", "..")
DIRS = {"F": "d", "B": "a", "U": "w", "D": "s"}
BUTTONS = {"HP": "u", "LP": "j", "HK": "o", "LK": "l", "BL": "i", "RN": "k"}


def fighter(fid):
    with open(os.path.join(ROOT, "data", "fighters", fid + ".json")) as f:
        return json.load(f)


def keys(step):
    """Keys held together for one step of arcade notation, e.g. 'F+HP' -> ['d', 'u']."""
    return [DIRS.get(p) or BUTTONS[p] for p in step.split("+")]


def specials(d):
    out = [(cmd, mid, False) for cmd, mid in d.get("commands", [])]
    out += [(cmd, mid, True) for cmd, mid in d.get("air_commands", [])]
    return out


def script(fid):
    d = fighter(fid)
    lines = ["# Specials of %s, generated by specials.py" % fid, "wait 4.0"]
    for cmd, mid, air in specials(d):
        mv = d["moves"].get(mid, {})
        lines += ["tap f4 60", "wait 1.0"]
        if mv.get("level") == "throw" or mv.get("requires") == "close":
            lines += ["hold d 1100"]
        if air:
            lines += ["tap w 60", "wait 0.3"]
        steps = cmd.split(",")
        for st in steps[:-1]:
            lines += ["chord %s 35" % " ".join(keys(st)), "wait 0.04"]
        lines += ["chord %s 60" % " ".join(keys(steps[-1])), "wait 0.35", "shot %s_%s" % (fid, mid), "wait 1.8"]
    lines += ["wait 1.0"]
    return "\n".join(lines) + "\n"


def check(fid, trace):
    d = fighter(fid)
    seen = set()
    with open(trace) as f:
        for ln in f:
            try:
                r = json.loads(ln)
            except json.JSONDecodeError:
                continue
            for e in r.get("ev", []):
                if e.get("type") == "move" and e.get("who") == 0:
                    seen.add(e.get("move"))
    missing = []
    for cmd, mid, air in specials(d):
        ok = mid in seen
        print("%-8s %-18s %-10s %s" % (fid, mid, cmd, "started" if ok else "NOT SEEN"))
        if not ok:
            missing.append(mid)
    return 1 if missing else 0


if __name__ == "__main__":
    if sys.argv[1] == "script":
        sys.stdout.write(script(sys.argv[2]))
    else:
        sys.exit(check(sys.argv[2], sys.argv[3]))
